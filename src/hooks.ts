import { useEffect, useState, useSyncExternalStore } from 'react';
import { vault } from './data/vault';
import { sync } from './sync/instance';

/** Re-render whenever the vault's in-memory metadata changes. */
export function useVault() {
  useSyncExternalStore(vault.subscribe, vault.getVersion);
  return vault;
}

export function useSyncStatus() {
  return useSyncExternalStore(sync.subscribe, sync.getStatus);
}

export function useMediaQuery(q: string): boolean {
  const [m, setM] = useState(() => window.matchMedia(q).matches);
  useEffect(() => {
    const mq = window.matchMedia(q);
    const on = () => setM(mq.matches);
    mq.addEventListener('change', on);
    return () => mq.removeEventListener('change', on);
  }, [q]);
  return m;
}

/** Stable pastel color per label so the same label always looks the same. */
export function labelHue(label: string): number {
  let h = 0;
  for (let i = 0; i < label.length; i++) h = (h * 31 + label.charCodeAt(i)) >>> 0;
  return h % 360;
}

export function timeAgo(ts: number): string {
  const s = Math.round((Date.now() - ts) / 1000);
  if (s < 45) return 'just now';
  const m = Math.round(s / 60);
  if (m < 60) return `${m}m ago`;
  const h = Math.round(m / 60);
  if (h < 24) return `${h}h ago`;
  const d = Math.round(h / 24);
  if (d < 7) return `${d}d ago`;
  return new Date(ts).toLocaleDateString();
}
